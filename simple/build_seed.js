/* Builds simple/seed.js from the real Drugs.com reviews in app/real_data.js.
   For each drug: how many reviews mention each symptom, and two short quotes.
   Run it from the repo root:  node simple/build_seed.js  */
const fs = require("fs");
const path = require("path");
const { findSymptoms } = require("./vocab.js");

const raw = fs.readFileSync(path.join(__dirname, "../app/real_data.js"), "utf8");
const data = JSON.parse(raw.slice(raw.indexOf("{"), raw.lastIndexOf("}") + 1));

/* One review is [id, drug index, rating, useful count, condition index, text] */
const QUOTES_PER_SYMPTOM = 2;

/* Keyword search cannot tell "the drug gave me anxiety" from "I take it for my anxiety".
   So we do not count, from the reviews, the symptoms of the illness the drug treats.
   People can still report them themselves in the app. */
const ILLNESS_SYMPTOMS = [
  [/depress|bipolar/i, ["depression", "mood changes"]],
  [/anxiety|panic/i, ["anxiety"]],
  [/insomnia/i, ["insomnia"]],
  [/weight loss|obesity/i, ["weight loss"]],
  [/acne/i, ["acne"]],
  [/pain|fibromyalgia/i, ["muscle pain", "joint pain"]]
];

function quoteAround(text, at){
  /* The sentence that contains the symptom, cut to about 170 characters */
  let start = Math.max(text.lastIndexOf(". ", at), text.lastIndexOf("! ", at), text.lastIndexOf("? ", at));
  start = start < 0 ? 0 : start + 2;
  let end = text.slice(at).search(/[.!?](\s|$)/);
  end = end < 0 ? text.length : at + end + 1;
  let q = text.slice(start, end).replace(/\s+/g, " ").replace(/&#039;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, "&").trim();
  if (q.length > 170) {
    const from = Math.max(0, at - start - 70);
    q = (from > 0 ? "… " : "") + q.slice(from, from + 165).trim() + "…";
  }
  return q;
}

const drugs = data.drugs.map((d, i) => {
  const reviews = data.reviews.filter(r => r[1] === i).sort((a, b) => b[3] - a[3]);
  const skip = ILLNESS_SYMPTOMS.filter(([re]) => d.cond.some(c => re.test(c))).flatMap(([, list]) => list);
  const symptoms = {};
  for (const r of reviews) {
    for (const [name, at] of findSymptoms(r[5])) {
      if (skip.includes(name)) continue;
      const s = symptoms[name] || (symptoms[name] = { n: 0, quotes: [] });
      s.n++;
      if (s.quotes.length < QUOTES_PER_SYMPTOM) s.quotes.push(quoteAround(r[5], at));
    }
  }
  return { name: d.name, cls: d.cls, reviews: reviews.length, leaflet: d.leaflet, skipped: [...new Set(skip)], symptoms };
});

const out = "/* Generated by simple/build_seed.js from the Drugs.com reviews. Do not edit by hand. */\n" +
  "window.VT_SEED = " + JSON.stringify({ source: "Drugs.com review dataset (UCI, Gräßer et al. 2018). Leaflets: FDA labels (openFDA).", drugs }) + ";\n";
fs.writeFileSync(path.join(__dirname, "seed.js"), out);
console.log("seed.js written:", drugs.length, "drugs,", Math.round(out.length / 1024), "KB");
