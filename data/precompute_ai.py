"""Runs the app's AI extraction once on every built-in real review and writes app/real_ai.js.
The app then opens with AI results for the 37 real drugs, with no API key needed by the viewer.

The prompt, the vocabulary and the model are read from app/index.html, so the results match
what the app's "Read with AI" button produces.

Usage: ANTHROPIC_API_KEY=sk-ant-... python3 data/precompute_ai.py
       (about 280 calls to the fast model; progress is cached in data/.cache/ai_results.json,
        so an interrupted run continues where it stopped)
Optional: ANTHROPIC_BASE_URL, VT_MODEL (overrides the model), VT_WORKERS (parallel calls, default 4)
"""
import datetime, json, os, pathlib, re, ssl, sys, time, urllib.error, urllib.request
from concurrent.futures import ThreadPoolExecutor
try:  # python.org builds on macOS ship without root certificates
    import certifi; SSL = ssl.create_default_context(cafile=certifi.where())
except ImportError:
    SSL = ssl.create_default_context()

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = (ROOT / "app" / "index.html").read_text()
CACHE = ROOT / "data" / ".cache" / "ai_results.json"
KEY = os.environ.get("ANTHROPIC_API_KEY") or sys.exit("Set ANTHROPIC_API_KEY first.")
BASE = os.environ.get("ANTHROPIC_BASE_URL", "https://api.anthropic.com").rstrip("/")
MODEL = os.environ.get("VT_MODEL") or re.search(r'API_MODEL_FAST="([^"]+)"', APP).group(1)
BATCH = 20

VOCAB = re.findall(r'^\s*"([^"]+)":/', re.search(r"const LEX = \{(.*?)\n\};", APP, re.S).group(1), re.M)
TEMPLATE = re.search(r"function aiPrompt\(batch, drug\)\{\n  return `(.*?)\n\$\{batch\.map", APP, re.S).group(1)

def prompt(batch, drug):
    p = TEMPLATE.replace("${drug}", drug).replace('${VOCAB.join(", ")}', ", ".join(VOCAB))
    assert "${" not in p, "the prompt in app/index.html changed: update precompute_ai.py"
    return p + "\n" + "\n".join(f"[{r[0]}] {r[5][:900]}" for r in batch)

def call(text):
    body = json.dumps({"model": MODEL, "max_tokens": 4000, "messages": [{"role": "user", "content": text}]}).encode()
    req = urllib.request.Request(BASE + "/v1/messages", body, {"content-type": "application/json", "x-api-key": KEY, "anthropic-version": "2023-06-01"})
    for attempt in range(6):
        try:
            with urllib.request.urlopen(req, timeout=120, context=SSL) as r:
                return "".join(c.get("text", "") for c in json.load(r)["content"])
        except urllib.error.HTTPError as e:
            if e.code in (401, 403): sys.exit("The API key was refused (HTTP %d)." % e.code)
            if e.code == 400: sys.exit("Bad request: " + e.read().decode()[:400])
            wait = 2 ** attempt * 3
        except (urllib.error.URLError, TimeoutError):
            wait = 2 ** attempt * 3
        time.sleep(wait)
    raise RuntimeError("the API kept failing")

def parse(text):  # same tolerance as sample.json in the app
    m = re.search(r"```(?:json)?\s*([\s\S]*?)```", text)
    raw = m.group(1) if m else text[min([i for i in (text.find("["), text.find("{")) if i >= 0] or [len(text)]):]
    out = json.loads(raw[: max(raw.rfind("]"), raw.rfind("}")) + 1])
    return out if isinstance(out, list) else out.get("results", [])

def run_batch(drug, batch):
    for attempt in range(3):
        try:
            got = {str(o.get("id", "")).strip("[] "): [str(e) for e in o.get("effects", []) if e] for o in parse(call(prompt(batch, drug))) if isinstance(o, dict)}
            return {r[0]: got.get(r[0], []) for r in batch}
        except (ValueError, json.JSONDecodeError):
            pass
    raise RuntimeError(f"unreadable answer for a {drug} batch")

def main():
    src = (ROOT / "app" / "real_data.js").read_text()
    data = json.loads(src[src.index("{"): src.rstrip().rindex(";")])
    done = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    if done.get("model") != MODEL: done = {"model": MODEL, "effects": {}}
    jobs = []
    for di, d in enumerate(data["drugs"]):
        todo = [r for r in data["reviews"] if r[1] == di and r[0] not in done["effects"]]
        jobs += [(d["name"], todo[i:i + BATCH]) for i in range(0, len(todo), BATCH)]
    print(f"model {MODEL}, {len(jobs)} calls to make ({len(done['effects'])} reviews already cached)")
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(int(os.environ.get("VT_WORKERS", "4"))) as pool:
        for n, res in enumerate(pool.map(lambda j: run_batch(*j), jobs), 1):
            done["effects"].update(res); CACHE.write_text(json.dumps(done))
            print(f"\r{n}/{len(jobs)} calls", end="", flush=True)
    print()
    ids = {r[0] for r in data["reviews"]}
    out = {"model": MODEL, "date": datetime.date.today().isoformat(), "effects": {k: v for k, v in done["effects"].items() if k in ids}}
    missing = len(ids) - len(out["effects"])
    (ROOT / "app" / "real_ai.js").write_text("/* Generated by data/precompute_ai.py: AI side effect extraction on the built-in real reviews. */\n"
                                             "window.VT_REAL_AI=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"app/real_ai.js written: {len(out['effects'])} reviews, {missing} missing")

if __name__ == "__main__":
    main()
